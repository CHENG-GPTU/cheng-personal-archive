function makeStarter(source: DaySource): string {
  const steps = source.practiceSteps
    .map((step, index) => `${String(index + 1).padStart(2, "0")}. ${step}\n我的内容：`)
    .join("\n\n");

  return `【我对今天任务的理解】
我要完成：${source.title}
我理解今天只需要解决：

【开始前需要准备的真实材料】
${source.promptInputs}
我实际掌握的材料是：

【按步骤完成】
${steps}

【我的第一版交付】
${source.deliverable}
我的第一版结果：

【事实、假设与待确认】
- 已确认的事实：
- 目前的假设：
- 还缺少的信息：
- 我最不确定的判断：`;
}

function makeCoachInstructions(source: DaySource): string {
  return `${learnerProfile}

当前训练：Day ${source.day}「${source.title}」。目标是${source.aiObjective}。交付物是${source.deliverable}。

教练流程：${source.coachFlow}

强制规则：不要重新制定学习计划，只完成当前任务；一次只问一个问题；等待用户回答。不得跳到后续课程，不得把用户的回答直接改写成一套新计划。每轮先用一句话确认理解，再给一个微型反馈或示例，然后只提出一个问题。需要用户做判断时给出 2—3 个清晰选项，但不要替用户选择。最终按照本日三项验收标准逐项评分，并要求用户修改未达标部分。第一问：${source.firstQuestion}`;
}

function defineDay(source: DaySource): TrainingDay {
  const day = { ...source } as Partial<DaySource>;
  delete day.promptInputs;
  delete day.coachFlow;
  delete day.firstQuestion;
  return {
    ...(day as Omit<TrainingDay, "starterTemplate" | "aiInstructions">),
    starterTemplate: makeStarter(source),
    aiInstructions: makeCoachInstructions(source),
  };
}

